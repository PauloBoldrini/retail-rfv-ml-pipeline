#!/usr/bin/env bash
set -euo pipefail

: "${PROJECT_ID:?Missing PROJECT_ID}"
: "${BQ_LOCATION:?Missing BQ_LOCATION}"
: "${RFV_DATASET:?Missing RFV_DATASET}"
: "${RFV_BUCKET:?Missing RFV_BUCKET}"
: "${CUSTOMER_MASTER_TABLE:?Missing CUSTOMER_MASTER_TABLE}"
: "${SALES_TABLE:?Missing SALES_TABLE}"
: "${RFV_BASE_TABLE:?Missing RFV_BASE_TABLE}"
: "${RFV_TRANSITIONS_TABLE:?Missing RFV_TRANSITIONS_TABLE}"
: "${RFV_RUNS_TABLE:?Missing RFV_RUNS_TABLE}"
: "${RFV_SERVICE_ACCOUNT:?Missing RFV_SERVICE_ACCOUNT}"
: "${HIGH_VALUE_CHURN_THRESHOLD:?Missing HIGH_VALUE_CHURN_THRESHOLD}"

FUNCTION_NAME="${RFV_FUNCTION_NAME:-rfv-pipeline}"
REGION="${BQ_LOCATION}"

gcloud functions deploy "${FUNCTION_NAME}" \
  --gen2 \
  --project="${PROJECT_ID}" \
  --region="${REGION}" \
  --runtime=python311 \
  --source=. \
  --entry-point=rfv_pipeline \
  --trigger-http \
  --service-account="${RFV_SERVICE_ACCOUNT}" \
  --memory=4GiB \
  --timeout=3600s \
  --max-instances=1 \
  --set-env-vars="PROJECT_ID=${PROJECT_ID},BQ_LOCATION=${BQ_LOCATION},RFV_DATASET=${RFV_DATASET},RFV_BUCKET=${RFV_BUCKET},CUSTOMER_MASTER_TABLE=${CUSTOMER_MASTER_TABLE},SALES_TABLE=${SALES_TABLE},RFV_BASE_TABLE=${RFV_BASE_TABLE},RFV_TRANSITIONS_TABLE=${RFV_TRANSITIONS_TABLE},RFV_RUNS_TABLE=${RFV_RUNS_TABLE},RFV_MODEL_PREFIX=${RFV_MODEL_PREFIX:-models/RFV_2.0},RFV_MODEL_VERSION=${RFV_MODEL_VERSION:-RFV_2.0},HIGH_VALUE_CHURN_THRESHOLD=${HIGH_VALUE_CHURN_THRESHOLD},CHURN_DAYS=${CHURN_DAYS:-180},NEW_CUSTOMER_DAYS=${NEW_CUSTOMER_DAYS:-30},MIN_PURCHASE_DAYS_FOR_MODEL=${MIN_PURCHASE_DAYS_FOR_MODEL:-3}"
